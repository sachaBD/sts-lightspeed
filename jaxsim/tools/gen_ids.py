"""Generate the Python views of the C++ enums: src/jaxsim/_core/tables/ids.py and python/src/sts_lightspeed/enums.py.

jaxsim ids are part of the observation contract (models embed them), so they are generated, committed and
checked by tests/test_ids.py. Rule for every vocabulary: id 0 = NONE (empty slot / invalid), then the C++
enum names in declaration order with the C++ sentinels (INVALID, EMPTY_POTION_SLOT) removed. The C++ oracle
maps by name, never by numeric value.

sts_lightspeed.enums: each ENUMS_VOCABS enum's names in declaration order, sentinels included, so a name's index is
its C++ value (the ids the simulator reads and writes).

Usage: python tools/gen_ids.py [--check]
"""
import re
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # sts-lightspeed
HEADERS = ROOT / "include" / "constants"
OUT = Path(__file__).resolve().parents[1] / "src" / "jaxsim" / "_core" / "tables" / "ids.py"
ENUMS = ROOT / "python" / "src" / "sts_lightspeed" / "enums.py"
ENUMS_VOCABS = ("CARDS", "RELICS", "POTIONS")  # those with a Python user

VOCABS = {  # python name: (header, C++ enum, sentinels dropped)
    "CARDS": ("Cards.h", "CardId", {"INVALID"}),
    "RELICS": ("Relics.h", "RelicId", {"INVALID"}),
    "POTIONS": ("Potions.h", "Potion", {"INVALID", "EMPTY_POTION_SLOT"}),
    "MOVES": ("MonsterMoves.h", "MonsterMoveId", {"INVALID"}),
    "PLAYER_STATUS": ("PlayerStatusEffects.h", "PlayerStatus", {"INVALID"}),
    "MONSTER_STATUS": ("MonsterStatusEffects.h", "MonsterStatus", {"INVALID"}),
}


def enum_names(header: Path, enum: str) -> list[str]:
    text = header.read_text()
    m = re.search(r"enum\s+class\s+" + enum + r"\s*:[^{]*\{(.*?)\};", text, re.S)
    if not m:
        raise SystemExit(f"enum {enum} not found in {header}")
    body = re.sub(r"//[^\n]*", "", m.group(1))
    names = []
    for item in body.split(","):
        item = item.strip()
        if not item:
            continue
        name, _, value = (p.strip() for p in item.partition("="))
        if value and names == [] and value != "0":
            raise SystemExit(f"{enum}: first value must be 0")
        if value and names:
            raise SystemExit(f"{enum}: explicit value on {name} not supported")
        names.append(name)
    return names


def render() -> str:
    lines = ['"""GENERATED by tools/gen_ids.py from include/constants/*.h. Do not edit."""', ""]
    for py, (header, enum, drop) in VOCABS.items():
        cpp = enum_names(HEADERS / header, enum)
        names = ["NONE"] + [n for n in cpp if n not in drop]
        lines.append(f"{py} = (")
        lines += [f'    "{n}",' for n in names]
        lines += [")", ""]
        lines.append(f"# C++ {enum} names by C++ value (for the oracle; not part of the contract)")
        lines.append(f"{py}_CPP = ({', '.join(repr(n) for n in cpp)},)")
        lines.append("")
    return "\n".join(lines)


def render_enums() -> str:
    lines = ['"""GENERATED by jaxsim/tools/gen_ids.py from include/constants/*.h. Do not edit.',
             "", 'Each C++ enum\'s names in declaration order: a name\'s index is its C++ value."""', ""]
    for py in ENUMS_VOCABS:
        header, enum, _ = VOCABS[py]
        names = ", ".join(f'"{n}"' for n in enum_names(HEADERS / header, enum))
        lines += [f"{py} = (  # sts::{enum}", textwrap.fill(names + ",", 116, initial_indent="    ",
                                                             subsequent_indent="    "), ")", ""]
    return "\n".join(lines)


def main():
    outputs = {OUT: render(), ENUMS: render_enums()}
    if "--check" in sys.argv:
        stale = [path.name for path, text in outputs.items() if path.read_text() != text]
        sys.exit(f"{', '.join(stale)} out of date: run python tools/gen_ids.py" if stale else 0)
    for path, text in outputs.items():
        path.write_text(text)
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
